const fashionProducts = categoryBlueprints.flatMap((blueprint, categoryIndex) =>
    blueprint.descriptors.map((descriptor, index) => {
        const brand = brands[(categoryIndex + index) % brands.length];
        const colors = pickCycle(blueprint.colors, index);
        const mainImage = pickCycle(imageMap[blueprint.category], index);
        const sizes =
            blueprint.sizeKey === 'accessories'
                ? sizeSets.accessories
                : blueprint.sizeKey === 'footwear'
                    ? sizeSets.footwear
                    : pickCycle(
                        [
                            sizeSets[blueprint.sizeKey],
                            [...sizeSets[blueprint.sizeKey], blueprint.sizeKey === 'dresses' ? 'XL' : 'XXL'],
                        ],
                        index
                    );
        const material = pickCycle(blueprint.materials, index);
        const fit = pickCycle(blueprint.fits, index);
        const occasion = pickCycle(blueprint.occasions, index);
        const season = pickCycle(blueprint.seasons, index);
        const styleTags = pickCycle(blueprint.styleTags, index);
        const gender = pickCycle(blueprint.genders, index);
        const isSponsored = index % 6 === 0;
        const isNewArrival = index % 4 === 0 || index === blueprint.descriptors.length - 1;

        return {
            name: `${brand} ${descriptor}`,
            image: mainImage,
            images: Array.from(new Set([mainImage, ...imageMap[blueprint.category]])),
            brand,
            category: blueprint.category,
            department: 'fashion',
            description: `${descriptor} delivers ${blueprint.descriptionTheme}. Finished in ${colors.join(' and ')} tones with a ${fit.toLowerCase()} fit, it suits ${occasion.toLowerCase()} plans across the ${season.toLowerCase()} season.`,
            price: blueprint.prices[index],
            countInStock: [18, 9, 4, 22, 14, 0, 6, 11, 3, 17][index],
            gender,
            colors,
            sizes,
            material,
            fit,
            occasion,
            season,
            styleTags,
            productType: blueprint.productType,
            isNewArrival,
            adminPriorityScore: 50 - index + categoryIndex,
            isSponsored,
            sponsoredWeight: isSponsored ? 12 - (index % 5) + (categoryIndex % 3) : 0,
        };
    })
);

